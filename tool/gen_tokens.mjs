#!/usr/bin/env node
// Generates packages/nightout_core/lib/src/theme/tokens.g.dart from the web
// repo's packages/ui/src/tokens.ts and theme.css, so the apps never carry a
// hand-copied colour. Usage:
//   node tool/gen_tokens.mjs           write the file
//   node tool/gen_tokens.mjs --check   exit 1 if the file is out of date
// The web repo defaults to ../../Nightout next to this repo; override with
// NIGHTOUT_WEB_DIR=/path/to/NightOut.

import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const repo = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const web = resolve(process.env.NIGHTOUT_WEB_DIR ?? join(repo, '../../Nightout'));
const uiSrc = join(web, 'packages/ui/src');
const out = join(repo, 'packages/nightout_core/lib/src/theme/tokens.g.dart');
const check = process.argv.includes('--check');

const tokens = await import(pathToFileURL(join(uiSrc, 'tokens.ts')).href);
const css = readFileSync(join(uiSrc, 'theme.css'), 'utf8');

// Same block lookup as packages/ui/src/tokens.test.ts.
function cssBlock(selector) {
  const start = css.indexOf(selector);
  if (start < 0) throw new Error(`theme.css has no "${selector}" block`);
  return css.slice(start, css.indexOf('}', start));
}

function cssVar(block, name) {
  const m = block.match(new RegExp(`--${name}:\\s*([^;]+);`));
  if (!m) throw new Error(`theme.css block is missing --${name}`);
  return m[1].trim();
}

const hex2 = (n) => Math.round(n).toString(16).padStart(2, '0').toUpperCase();

function dartColor(css, block) {
  const v = css.trim();
  const ref = v.match(/^var\(--([a-z-]+)\)$/);
  if (ref) return dartColor(cssVar(block, ref[1]), block);
  const hex = v.match(/^#([0-9a-f]{6})$/i);
  if (hex) return `Color(0xFF${hex[1].toUpperCase()})`;
  const rgba = v.match(/^rgba\((\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\)$/);
  if (rgba) {
    const [, r, g, b, a] = rgba.map(Number);
    return `Color(0x${hex2(a * 255)}${hex2(r)}${hex2(g)}${hex2(b)})`;
  }
  throw new Error(`unsupported colour "${v}"`);
}

// CSS box-shadow list -> Dart BoxShadow list. Splits on commas outside parens.
function dartShadows(value, block) {
  const parts = value.split(/,(?![^(]*\))/).map((s) => s.trim());
  return parts.map((part) => {
    const colorStart = part.search(/(var\(|rgba\(|#)/);
    const lengths = part.slice(0, colorStart).trim().split(/\s+/).map((s) => parseFloat(s));
    const [x = 0, y = 0, blur = 0, spread = 0] = lengths;
    const args = [`color: ${dartColor(part.slice(colorStart), block)}`];
    if (x || y) args.push(`offset: Offset(${x}, ${y})`);
    if (blur) args.push(`blurRadius: ${blur}`);
    if (spread) args.push(`spreadRadius: ${spread}`);
    return `BoxShadow(${args.join(', ')})`;
  });
}

function palette(mode) {
  const block = cssBlock(mode === 'dark' ? ':root,' : '.light {');
  const fields = Object.entries(tokens.colors[mode]).map(
    ([k, v]) => `  ${k}: ${dartColor(v, block)},`,
  );
  fields.push(`  heroVia: ${dartColor(cssVar(block, 'hero-via'), block)},`);
  fields.push(`  titleFrom: ${dartColor(cssVar(block, 'title-from'), block)},`);
  fields.push(`  titleTo: ${dartColor(cssVar(block, 'title-to'), block)},`);
  fields.push(`  glow: [${dartShadows(cssVar(block, 'glow'), block).join(', ')}],`);
  return `const _${mode} = NightOutColors(\n${fields.join('\n')}\n);`;
}

const ms = (s) => `Duration(milliseconds: ${Math.round(s * 1000)})`;
const { duration, ease, spring } = tokens.motionTokens;
const tiers = Object.entries(tokens.tierColors).map(
  ([k, t]) =>
    `const _tier${k} = (background: ${dartColor(t.bg)}, foreground: ${dartColor(t.fg)}, label: '${t.label}');`,
);

const source = `// GENERATED by tool/gen_tokens.mjs from NightOut-Org/NightOut
// packages/ui/src/tokens.ts and theme.css. Do not edit by hand.

part of 'tokens.dart';

${palette('dark')}

${palette('light')}

const _fast = ${ms(duration.fast)};
const _base = ${ms(duration.base)};
const _slow = ${ms(duration.slow)};
const _easeOut = Cubic(${ease.out.join(', ')});
const _sheetStiffness = ${spring.sheet.stiffness}.0;
const _sheetDamping = ${spring.sheet.damping}.0;

const _radiusBase = ${tokens.radius.base}.0;
const _radiusPill = ${tokens.radius.pill}.0;

${tiers.join('\n')}
`;

// Format through dart so the file is stable under \`dart format .\`.
const tmp = mkdtempSync(join(tmpdir(), 'gen-tokens-'));
const tmpFile = join(tmp, 'tokens.g.dart');
writeFileSync(tmpFile, source);
execFileSync('dart', ['format', '--language-version=3.11', tmpFile], { stdio: 'ignore' });
const formatted = readFileSync(tmpFile, 'utf8');
rmSync(tmp, { recursive: true });

if (check) {
  let current = '';
  try {
    current = readFileSync(out, 'utf8');
  } catch {}
  if (current !== formatted) {
    console.error(`${out} is out of date with ${uiSrc}. Run: node tool/gen_tokens.mjs`);
    process.exit(1);
  }
  console.log('tokens.g.dart matches web tokens');
} else {
  writeFileSync(out, formatted);
  console.log(`wrote ${out}`);
}
